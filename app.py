def resource_path(relative):
    base = getattr(sys, "_MEIPASS", os.path.dirname(os.path.abspath(__file__)))
    return os.path.join(base, relative)


def database_url():
    url = os.environ.get("DATABASE_URL", "").strip()
    if not url:
        # Local development only. Production deployment must set DATABASE_URL.
        local_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "printing_yassine_dev.db")
        return "sqlite:///" + local_path.replace("\\", "/")
    # Render and some providers still supply postgres:// URLs.
    if url.startswith("postgres://"):
        url = "postgresql+psycopg://" + url[len("postgres://"):]
    elif url.startswith("postgresql://") and "+psycopg" not in url:
        url = "postgresql+psycopg://" + url[len("postgresql://"):]
    return url


app = Flask(__name__, template_folder=resource_path("templates"), static_folder=resource_path("static"))
_secret_key = os.environ.get("SECRET_KEY")
if not _secret_key and os.environ.get("PORT"):
    raise RuntimeError("SECRET_KEY doit être défini dans l'environnement du serveur de production.")
app.secret_key = _secret_key or "DEV-ONLY-change-this-secret-before-deployment"
app.config.update(
    SESSION_COOKIE_HTTPONLY=True,
    SESSION_COOKIE_SAMESITE="Lax",
    SESSION_COOKIE_SECURE=os.environ.get("COOKIE_SECURE", "true").lower() in ("1", "true", "yes"),
    PERMANENT_SESSION_LIFETIME=60 * 60 * 12,
)
engine = create_engine(database_url(), pool_pre_ping=True, pool_recycle=300, future=True)
lock = threading.RLock()
DATA_VERSION = "2026-10-central-v1"


def init_db():
    with engine.begin() as conn:
        conn.execute(text("""CREATE TABLE IF NOT EXISTS users (
            id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
            email VARCHAR(254) NOT NULL UNIQUE,
            password_hash VARCHAR(512) NOT NULL,
            role VARCHAR(30) NOT NULL DEFAULT 'user',
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        )"""))
        # SQLite does not support GENERATED BY DEFAULT AS IDENTITY on all versions.
        # If needed, create the SQLite-compatible version.
        conn.execute(text("""CREATE TABLE IF NOT EXISTS app_storage (
            key VARCHAR(255) PRIMARY KEY,
            value TEXT NOT NULL,
            updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        )"""))
        conn.execute(text("""CREATE TABLE IF NOT EXISTS app_meta (
            key VARCHAR(100) PRIMARY KEY,
            value VARCHAR(255) NOT NULL
        )"""))
        conn.execute(text("INSERT INTO app_meta(key,value) VALUES('data_version', :v) ON CONFLICT (key) DO NOTHING"), {"v": DATA_VERSION})


def create_admin_from_env():
    email = os.environ.get("ADMIN_EMAIL", "").strip().lower()
    password = os.environ.get("ADMIN_PASSWORD", "")
    if not email or not password:
        return
    if len(password) < 12:
        raise RuntimeError("ADMIN_PASSWORD doit contenir au moins 12 caractères.")
    with engine.begin() as conn:
        existing = conn.execute(text("SELECT id FROM users WHERE email=:email"), {"email": email}).first()
        if not existing:
            conn.execute(text("INSERT INTO users(email,password_hash,role) VALUES(:email,:hash,'admin')"), {
                "email": email, "hash": generate_password_hash(password)
            })


# Use portable ID definitions for SQLite and PostgreSQL.
def ensure_schema():
    dialect = engine.dialect.name
    id_sql = "INTEGER PRIMARY KEY AUTOINCREMENT" if dialect == "sqlite" else "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    with engine.begin() as conn:
        conn.execute(text(f"CREATE TABLE IF NOT EXISTS users (id {id_sql}, email VARCHAR(254) NOT NULL UNIQUE, password_hash VARCHAR(512) NOT NULL, role VARCHAR(30) NOT NULL DEFAULT 'user', created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP)"))
        conn.execute(text("CREATE TABLE IF NOT EXISTS app_storage (key VARCHAR(255) PRIMARY KEY, value TEXT NOT NULL, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP)"))
        conn.execute(text("CREATE TABLE IF NOT EXISTS app_meta (key VARCHAR(100) PRIMARY KEY, value VARCHAR(255) NOT NULL)"))
        if dialect == "sqlite":
            conn.execute(text("INSERT OR IGNORE INTO app_meta(key,value) VALUES('data_version', :v)"), {"v": DATA_VERSION})
        else:
            conn.execute(text("INSERT INTO app_meta(key,value) VALUES('data_version', :v) ON CONFLICT (key) DO NOTHING"), {"v": DATA_VERSION})


def login_required(view):
    @wraps(view)
    def wrapped(*args, **kwargs):
        if not session.get("user_id"):
            if request.path.startswith("/api/"):
                return jsonify({"ok": False, "error": "Non authentifié"}), 401
            return redirect(url_for("login", next=request.path))
        return view(*args, **kwargs)
    return wrapped


@app.after_request
def security_headers(response):
    response.headers.setdefault("X-Content-Type-Options", "nosniff")
    response.headers.setdefault("X-Frame-Options", "SAMEORIGIN")
    response.headers.setdefault("Referrer-Policy", "strict-origin-when-cross-origin")
    return response


@app.get("/")
@login_required
def home():
    return render_template("index.html")


@app.route("/login", methods=["GET", "POST"])
def login():
    if session.get("user_id"):
        return redirect(url_for("home"))
    error = None
    if request.method == "POST":
        email = (request.form.get("email") or "").strip().lower()
        password = request.form.get("password") or ""
        with engine.connect() as conn:
            user = conn.execute(text("SELECT id,email,password_hash,role FROM users WHERE email=:email"), {"email": email}).mappings().first()
        if user and check_password_hash(user["password_hash"], password):
            session.clear()
            session.permanent = True
            session["user_id"] = user["id"]
            session["email"] = user["email"]
            session["role"] = user["role"]
            target = request.args.get("next", "")
            if target.startswith("/") and not target.startswith("//"):
                return redirect(target)
            return redirect(url_for("home"))
        error = "E-mail ou mot de passe incorrect."
    return render_template("login.html", error=error)


@app.post("/logout")
@login_required
def logout():
    session.clear()
    return redirect(url_for("login"))


@app.get("/api/state")
@login_required
def get_state():
    try:
        with engine.connect() as conn:
            rows = conn.execute(text("SELECT key,value FROM app_storage")).fetchall()
        return jsonify({row[0]: row[1] for row in rows})
    except SQLAlchemyError:
        app.logger.exception("Lecture de l'état impossible")
        return jsonify({"error": "Erreur de base de données"}), 500


@app.post("/api/state")
@login_required
def save_state():
    payload = request.get_json(silent=True)
    if not isinstance(payload, dict) or len(payload) > 5000:
        return jsonify({"ok": False, "error": "État invalide"}), 400
    try:
        # Snapshot compatibility with the existing frontend. Concurrent edits to the
        # same snapshot are last-write-wins; see README before multi-user production use.
        clean_payload = {k: v for k, v in payload.items() if isinstance(k, str) and k != "__data_version" and isinstance(v, str)}
        with lock, engine.begin() as conn:
            current_keys = [r[0] for r in conn.execute(text("SELECT key FROM app_storage")).fetchall()]
            for old_key in current_keys:
                if old_key not in clean_payload:
                    conn.execute(text("DELETE FROM app_storage WHERE key=:k"), {"k": old_key})
            for key, value in clean_payload.items():
                conn.execute(text("""INSERT INTO app_storage(key,value,updated_at) VALUES(:k,:v,CURRENT_TIMESTAMP)
                    ON CONFLICT(key) DO UPDATE SET value=excluded.value, updated_at=CURRENT_TIMESTAMP"""), {"k": key, "v": value})
        return jsonify({"ok": True})
    except SQLAlchemyError:
        app.logger.exception("Sauvegarde de l'état impossible")
        return jsonify({"ok": False, "error": "Erreur de base de données"}), 500


@app.post("/api/reset")
@login_required
def reset_state():
    if session.get("role") != "admin":
        return jsonify({"ok": False, "error": "Réservé à l'administrateur"}), 403
    try:
        with engine.begin() as conn:
            conn.execute(text("DELETE FROM app_storage"))
        return jsonify({"ok": True, "message": "Données métier réinitialisées."})
    except SQLAlchemyError:
        app.logger.exception("Réinitialisation impossible")
        return jsonify({"ok": False, "error": "Erreur de base de données"}), 500


@app.get("/api/health")
def health():
    try:
        with engine.connect() as conn:
            conn.execute(text("SELECT 1"))
        return jsonify({"ok": True, "database": engine.dialect.name})
    except SQLAlchemyError:
        return jsonify({"ok": False, "database": "unavailable"}), 503


